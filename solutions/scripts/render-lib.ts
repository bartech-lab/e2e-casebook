export type CaseScore = { app: string; date: string; runs: number; workers: number; approaches: string[]; rows: string[][] };

export const BEGIN = '<!-- score: generated by npm run render-cards, do not edit by hand -->';
export const END = '<!-- /score -->';

export const label = (approach: string) => approach.replace('-', ' ').replaceAll('-', ' ');

export function renderBlock(s: CaseScore): string {
  return [
    BEGIN,
    `Scored with \`npm run score\` on ${s.date}: ${s.runs} runs per row, ${s.workers} workers, app ${s.app}.`,
    `A bug counts as caught only when the approach failed in all ${s.runs} runs and passed all ${s.runs} on the clean build.`,
    '',
    `| Planted bug | ${s.approaches.map(label).join(' | ')} |`,
    `|---|${s.approaches.map(() => '---').join('|')}|`,
    ...s.rows.map((r) => `| ${r.join(' | ')} |`),
    END,
  ].join('\n');
}

export function replaceBlock(card: string, block: string): string {
  const start = card.indexOf(BEGIN);
  const end = card.indexOf(END);
  if (start < 0 || end < start) throw new Error('the card has no score block');
  if (card.indexOf(BEGIN, start + 1) >= 0) throw new Error('the card has two score blocks');
  return card.slice(0, start) + block + card.slice(end + END.length);
}
